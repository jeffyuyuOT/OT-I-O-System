// ============================================================
// 收據掃描模組(選配)
// 這個檔案是獨立收據掃描服務(receipt-scan-service)在前端這邊的開關。跟 ot-custom-features.js
// 裡的那幾個不一樣——這個不是 Orange Tea 自己的業務規則客製,而是「有沒有接這個獨立掃描服務」
// 這件事本身:接了才有意義的功能就開在這裡,理論上以後其他倉庫系統也可能共用同一個掃描服務、
// 用同一個開關檔案。
//
// 沒有這個模組(部署時沒帶這個檔案)的話:
//   - 登記進出貨→進貨上傳收據時,不會出現「掃描收據自動帶入商品」按鈕(附件上傳本身不受影響)
//   - 倉庫後台管理裡不會有「收據掃描數據庫」這個子分頁
// index.html 裡引用這個檔案的那行 <script src="receipt-scan-features.js"></script> 留著沒關係,
// 瀏覽器抓不到檔案只會在 console 顯示一個 404,不影響其他功能運作。
//
// window.FEATURES 用 Object.assign 合併寫入,不要整包蓋掉——理由跟 ot-custom-features.js
// 裡的說明一樣,兩個檔案都會寫入同一個 window.FEATURES,不管誰先載入都要能疊加。
// ============================================================
window.FEATURES = window.FEATURES || {};
Object.assign(window.FEATURES, {
  // 登記進出貨→進貨的「掃描收據自動帶入商品」按鈕,以及倉庫後台管理裡的「收據掃描數據庫」
  // 子分頁(收據文字對商品的記憶對照表)
  receiptScanModule: true
});
