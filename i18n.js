function t(key){
  return (I18N[lang] && I18N[lang][key]) || I18N.zh[key] || key;
}

function tn(key, n){
  return t(key).replace('{n}', n);
}

// 支援多個具名參數的翻譯替換,例如 tf('partyProductPanelDesc', {name: party.name})
function tf(key, params){
  let s = t(key);
  Object.keys(params || {}).forEach(k => { s = s.split('{' + k + '}').join(params[k]); });
  return s;
}

async function setLang(newLang){
  lang = newLang;
  try{ localStorage.setItem('inventoryAppLang', lang); } catch(e){}
  try{ await dbSet('lang', lang); } catch(e){}
  applyStaticTranslations();
  renderCurrentUserBadge();
  updateAppHeaderTitle();
  renderTabBar();
  renderAll();
  setTxType(currentTxType);
}

function toggleLang(){
  setLang(lang === 'zh' ? 'en' : 'zh');
}

