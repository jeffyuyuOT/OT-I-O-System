-- ============================================================
-- Invoice 變更紀錄(訂單改了內容,Invoice 跟著更新時留下的紀錄)
-- 在「測試」Supabase 專案的 SQL Editor 執行一次;正式版等你明說再執行。可重複執行。
-- 前提:已經執行過 sql/invoices_table.sql 與 sql/invoice_payments.sql。
--
-- * invoice_changes:每次 Invoice 因為訂單變更而更新,就多一列(誰、什麼時候、總額前後、變更內容 detail)。
-- * invoices.change_count:這張 Invoice 被更新過幾次(清單用來顯示「已變更」圖示)。
-- * invoice_sync():更新 Invoice 的明細與總額(號碼、日期、已收款不變),同時寫一筆變更紀錄。
-- * 備份 / 還原:一併處理變更紀錄。
-- ============================================================
alter table public.invoices add column if not exists change_count int default 0;

create table if not exists public.invoice_changes (
  id           bigint generated by default as identity primary key,
  invoice_id   text not null references public.invoices(id) on delete cascade,
  changed_at   timestamptz not null default now(),
  changed_by   text,
  before_total numeric,
  after_total  numeric,
  detail       jsonb
);
create index if not exists invoice_changes_invoice_idx on public.invoice_changes (invoice_id, changed_at);

alter table public.invoice_changes enable row level security;
drop policy if exists invoice_changes_select on public.invoice_changes;
create policy invoice_changes_select on public.invoice_changes for select to authenticated using (public.is_accounting_user());

create or replace function public.invoice_sync(p_invoice_id text, p_snapshot jsonb, p_detail jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_inv public.invoices%rowtype; v_snap jsonb; v_who text;
begin
  if not public.is_accounting_user() then raise exception 'invoice_forbidden'; end if;
  select * into v_inv from public.invoices where id = p_invoice_id for update;
  if not found then raise exception 'invoice_not_found'; end if;
  -- 號碼、id、日期、已收款不隨訂單變動
  v_snap := p_snapshot || jsonb_build_object('no', v_inv.invoice_no, 'id', v_inv.id, 'paid', coalesce(v_inv.paid, 0));
  select username into v_who from public.profiles where id = auth.uid();
  update public.invoices
     set snapshot = v_snap,
         before_tax = (v_snap->>'beforeTax')::numeric,
         tax = (v_snap->>'tax')::numeric,
         total = (v_snap->>'total')::numeric,
         order_no = coalesce(nullif(v_snap->>'orderNo', ''), order_no),
         change_count = coalesce(change_count, 0) + 1
   where id = p_invoice_id;
  insert into public.invoice_changes (invoice_id, changed_by, before_total, after_total, detail)
  values (p_invoice_id, v_who, v_inv.total, (v_snap->>'total')::numeric, p_detail);
  return jsonb_build_object('id', p_invoice_id, 'total', (v_snap->>'total')::numeric);
end $$;

-- 備份 / 還原:多一個 p_changes(舊簽章移除)
drop function if exists public.invoice_restore_all(jsonb, bigint, jsonb);
create or replace function public.invoice_restore_all(p_rows jsonb, p_next bigint, p_payments jsonb default '[]'::jsonb, p_changes jsonb default '[]'::jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin_user() then raise exception 'invoice_forbidden'; end if;
  delete from public.invoices where true;   -- 收款與變更紀錄會跟著 cascade 刪除
  insert into public.invoices
    select * from jsonb_populate_recordset(null::public.invoices, coalesce(p_rows, '[]'::jsonb));
  insert into public.invoice_payments
    select * from jsonb_populate_recordset(null::public.invoice_payments, coalesce(p_payments, '[]'::jsonb));
  insert into public.invoice_changes
    select * from jsonb_populate_recordset(null::public.invoice_changes, coalesce(p_changes, '[]'::jsonb));
  -- 舊版備份(沒有收款資料):把快照裡的 Paid Today 轉成一筆收款
  insert into public.invoice_payments (id, invoice_id, pay_date, amount, method, created_by)
  select gen_random_uuid()::text, i.id, i.invoice_date, least((i.snapshot->>'paid')::numeric, i.total), 'Paid Today', i.created_by
    from public.invoices i
   where coalesce(nullif(i.snapshot->>'paid', '')::numeric, 0) > 0
     and not exists (select 1 from public.invoice_payments p where p.invoice_id = i.id);
  update public.invoices i set paid = coalesce((select sum(amount) from public.invoice_payments p where p.invoice_id = i.id), 0) where true;
  update public.invoices i set change_count = coalesce((select count(*) from public.invoice_changes c where c.invoice_id = i.id), 0) where true;
  update public.invoice_counter set next_no = greatest(coalesce(p_next, 1), 1) where id = 1;
end $$;

revoke all on function public.invoice_sync(text, jsonb, jsonb) from public, anon;
revoke all on function public.invoice_restore_all(jsonb, bigint, jsonb, jsonb) from public, anon;
grant execute on function public.invoice_sync(text, jsonb, jsonb) to authenticated;
grant execute on function public.invoice_restore_all(jsonb, bigint, jsonb, jsonb) to authenticated;
